function menuName(name, lang) {
  return localizedMenuNames[lang]?.[name] || name;
}

function renderMenu(lang) {
  document.querySelectorAll("[data-menu]").forEach((container) => {
    const group = container.dataset.menu;
    container.innerHTML = "";

    menu[group].forEach(([name, price, note]) => {
      const item = document.createElement("div");
      item.className = "menu-item";

      const text = document.createElement("span");
      const title = document.createElement("span");
      title.className = "menu-name";
      title.textContent = menuName(name, lang);

      const detail = document.createElement("small");
      detail.textContent = noteLabels[lang][note];

      text.append(title, detail);

      const cost = document.createElement("span");
      cost.className = "menu-price";
      cost.textContent = `${price} ${copy[lang].currency}`;

      item.append(text, cost);
      container.append(item);
    });
  });
}

function setLanguage(lang) {
  const messages = copy[lang];
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = messages[element.dataset.i18n] || element.textContent;
  });

  document.querySelectorAll(".language-button").forEach((button) => {
    const active = button.dataset.lang === lang;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  renderMenu(lang);
}

document.querySelectorAll(".language-button").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

setLanguage("ar");
